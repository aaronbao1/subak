"""Deterministic daily per-person billing export for the Northstar seed (all values simulated).

frontend-integration-design §3. `rows()` is pure (no randomness, no clock): it splits each team x
category target of the shared table over the people and days Oct 1-20 with a largest-remainder rule
(quantum one dollar), so every team and category sums exactly to the committed totals:

    research 45,000 (5,000 seats + 40,000 API), product 20,000 (4,000 seats + 16,000 overage),
    engineering 30,000 (4,000 seats + 26,000 API); included usage notional 3,000 / 2,500.

Included-usage rows are team-level (no `user_email`): providers report pooled seat usage per workspace.
They carry no charge, so person spend sums exactly to team spend.

    python -m app.seed.daily_spend --write   # regenerate the seed export and planted 01/02
    python -m app.seed.daily_spend --check   # exit 1 if a committed file differs

The three files are always generated by this script and never edited by hand.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from dataclasses import dataclass
from datetime import date, timedelta
from fractions import Fraction
from pathlib import Path

from app.config import BACKEND_ROOT
from app.seed.northstar import PEOPLE, SPEND_FILE

PLANTED_DIR = BACKEND_ROOT / "seed" / "planted"
PLANTED_DUPLICATE = PLANTED_DIR / "01_duplicate_billing_export.csv"
PLANTED_REEXPORT = PLANTED_DIR / "02_reexported_billing_export.csv"

COLUMNS = (
    "record_id", "occurred_at", "source_account", "user_email", "provider", "model", "cost_category",
    "value_kind", "amount", "unit", "notional_value", "input_tokens", "output_tokens", "description",
)
FIRST_DAY = date(2026, 10, 1)
LAST_DAY = date(2026, 10, 20)  # data as-of; the export closes at the end of this day
DATES = tuple(FIRST_DAY + timedelta(days=i) for i in range((LAST_DAY - FIRST_DAY).days + 1))
SUFFIX = " (simulated daily export)"


@dataclass(frozen=True)
class Target:
    team: str
    account: str
    provider: str
    category: str
    model: str | None
    amount: int | None  # whole dollars of counted spend (None for included usage)
    notional: int | None  # whole dollars of list value (included usage only)
    input_tokens: int | None
    output_tokens: int | None
    team_level: bool
    description: str


TARGETS: tuple[Target, ...] = (
    Target("research", "ws-research", "anthropic", "subscription_fee", None, 5000, None, None, None, False,
           "research team plan seats"),
    Target("research", "ws-research", "anthropic", "direct_api", "claude", 40000, None, 1_000_000, 200_000, False,
           "evaluation harness API usage"),
    Target("research", "ws-research", "anthropic", "included_usage", "claude", None, 3000, 500_000, 100_000, True,
           "usage covered by research seats"),
    Target("product", "ws-product", "openai", "subscription_fee", None, 4000, None, None, None, False,
           "product team plan seats"),
    Target("product", "ws-product", "openai", "billable_overage", "gpt", 16000, None, None, None, False,
           "launch tuning beyond included usage"),
    Target("engineering", "ws-engineering", "anthropic", "subscription_fee", None, 4000, None, None, None, False,
           "coding assistant seats"),
    Target("engineering", "ws-engineering", "anthropic", "included_usage", "claude", None, 2500, 400_000, 80_000,
           True, "usage covered by coding seats"),
    Target("engineering", "ws-engineering", "anthropic", "direct_api", "claude", 26000, None, None, None, False,
           "platform migration API usage"),
)


def dow(category: str, d: date) -> int:
    """Seat fees accrue evenly; usage is three times heavier on weekdays."""
    if category == "subscription_fee":
        return 1
    return 3 if d.weekday() < 5 else 1


def trend(person: dict, category: str, d: date) -> int:
    """Usage-level percent for a person on a day (100 by default). Seat fees are not affected: a person who
    moves to a cheaper model or pauses work keeps the seat."""
    if category == "subscription_fee":
        return 100
    t = person.get("trend")
    if t and d >= t[1]:
        return t[0]
    return 100


def active(person: dict, d: date) -> int:
    start = person.get("active_from")
    return 0 if start is not None and d < start else 1


def base(person: dict, category: str) -> int:
    return 1 if category == "subscription_fee" else person["usage_base"]


def split(total: int, weights: list[int]) -> list[int]:
    """Largest-remainder split of `total` whole units over integer weights. Ties go to the earlier cell."""
    w_sum = sum(weights)
    if w_sum <= 0:
        raise ValueError("split needs a positive weight")
    quotas = [Fraction(total * w, w_sum) for w in weights]
    floors = [q.numerator // q.denominator for q in quotas]
    remainder = total - sum(floors)
    order = sorted(range(len(weights)), key=lambda i: (-(quotas[i] - floors[i]), i))
    for i in order[:remainder]:
        floors[i] += 1
    return floors


def _cells(t: Target) -> list[tuple[date, dict | None, int]]:
    """(date, person or None for team-level, weight) for every cell with weight > 0, ordered by
    (date, person_id)."""
    if t.team_level:
        return [(d, None, dow(t.category, d)) for d in DATES]
    members = sorted((p for p in PEOPLE if p["team"] == t.team), key=lambda p: p["id"])
    cells = []
    for d in DATES:
        for p in members:
            w = base(p, t.category) * trend(p, t.category, d) * dow(t.category, d) * active(p, d)
            if w > 0:
                cells.append((d, p, w))
    return cells


def _money(units: int) -> str:
    return f"{units}.00"


def rows() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for t in TARGETS:
        cells = _cells(t)
        weights = [w for _, _, w in cells]
        amounts = split(t.amount, weights) if t.amount is not None else None
        notionals = split(t.notional, weights) if t.notional is not None else None
        tin = split(t.input_tokens, weights) if t.input_tokens is not None else None
        tout = split(t.output_tokens, weights) if t.output_tokens is not None else None
        for i, (d, person, _) in enumerate(cells):
            who = person["id"] if person else t.team
            out.append({
                "record_id": f"ns-2026p1-{d:%Y%m%d}-{who}-{t.category}",
                "occurred_at": f"{d.isoformat()}T00:00:00Z",
                "source_account": t.account,
                "user_email": person["email"] if person else "",
                "provider": t.provider,
                "model": t.model or "",
                "cost_category": t.category,
                "value_kind": "simulated",
                "amount": _money(amounts[i]) if amounts is not None else "",
                "unit": "USD",
                "notional_value": _money(notionals[i]) if notionals is not None else "",
                "input_tokens": str(tin[i]) if tin is not None else "",
                "output_tokens": str(tout[i]) if tout is not None else "",
                "description": t.description + SUFFIX,
            })
    out.sort(key=lambda r: r["record_id"])
    return out


def render_csv(records: list[dict[str, str]], *, columns: tuple[str, ...] = COLUMNS,
               line_end: str = "\n") -> bytes:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=list(columns), lineterminator=line_end)
    writer.writeheader()
    writer.writerows(records)
    return buf.getvalue().encode("utf-8")


def render_files() -> dict[Path, bytes]:
    records = rows()
    seed = render_csv(records)
    reexport = render_csv(list(reversed(records)), columns=tuple(reversed(COLUMNS)), line_end="\r\n")
    return {SPEND_FILE: seed, PLANTED_DUPLICATE: seed, PLANTED_REEXPORT: reexport}


def check() -> list[Path]:
    """Committed files that differ from the generated bytes."""
    return [p for p, data in render_files().items() if not p.exists() or p.read_bytes() != data]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.seed.daily_spend", description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the seed export and planted 01/02")
    mode.add_argument("--check", action="store_true", help="exit 1 if a committed file differs")
    args = parser.parse_args(argv)
    if args.write:
        for path, data in render_files().items():
            path.write_bytes(data)
            print(f"wrote {path.relative_to(BACKEND_ROOT)} ({len(data)} bytes)")
        return 0
    stale = check()
    for path in stale:
        print(f"differs: {path.relative_to(BACKEND_ROOT)} (run python -m app.seed.daily_spend --write)")
    if not stale:
        print(f"daily spend export up to date ({len(rows())} records)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
